function client(connectionString: string): Db {
  return new PrismaClient({ adapter: new PrismaPg({ connectionString }) });
}

// Same write shape as saveSections(): upsert the Page, then replace ALL its sections.
async function writePage(db: Db, seed: PageSeed) {
  const page = await db.page.upsert({
    where: { slug: seed.slug },
    update: {
      titleTh: seed.titleTh,
      titleEn: seed.titleEn,
      status: "PUBLISHED",
      archived: false,
      seoTitle: seed.seoTitle,
      seoDesc: seed.seoDesc,
    },
    create: {
      slug: seed.slug,
      titleTh: seed.titleTh,
      titleEn: seed.titleEn,
      status: "PUBLISHED",
      seoTitle: seed.seoTitle,
      seoDesc: seed.seoDesc,
    },
  });

  await db.pageSection.deleteMany({ where: { pageId: page.id } });

  for (let i = 0; i < seed.sections.length; i++) {
    const s = seed.sections[i];
    await db.pageSection.create({
      data: {
        pageId: page.id,
        order: i,
        type: "COMPANY_INTRO",
        titleTh: s.titleTh,
        titleEn: null,
        visibleDesktop: true,
        visibleTablet: true,
        visibleMobile: true,
        columns: null,
        itemsToShow: null,
        config: { sourceLabel: SOURCE_LABEL, anchorId: "", bodyTh: s.bodyTh, imageUrl: "" },
      },
    });
  }
  console.log("  page " + seed.slug + ": " + seed.sections.length + " section(s)");
}

// Same write as the "เปิดใช้งาน" toggle on /admin/site/widgets.
async function enableCookieConsent(db: Db) {
  const row = await db.widget.findUnique({ where: { key: "cookie-consent" } });
  if (!row) {
    console.warn('  !! widget "cookie-consent" not found — nothing to enable');
    return;
  }
  await db.widget.update({ where: { key: "cookie-consent" }, data: { enabled: true } });
  console.log("  widget cookie-consent: enabled");
}

async function applyAll(label: string, connectionString: string) {
  console.log("\n[" + label + "]");
  const db = client(connectionString);
  try {
    await writePage(db, PRIVACY_POLICY);
    await writePage(db, COOKIE_POLICY);
    await enableCookieConsent(db);
  } finally {
    await db.$disconnect();
  }
}

async function main() {
  if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL is not set");
  await applyAll("primary/Supabase", process.env.DATABASE_URL);

  const local = process.env.LOCAL_DATABASE_URL;
  if (!local) {
    console.warn("\n!! LOCAL_DATABASE_URL is not set — local backup NOT updated");
    return;
  }
  try {
    await applyAll("local", local);
  } catch (err) {
    console.warn("\n!! local backup NOT updated: " + (err instanceof Error ? err.message : String(err)));
  }
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
